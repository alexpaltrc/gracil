pub use selection::title;

/// The class File Explorer asks for. The package manifest names the same value.
pub const CLSID: GUID = GUID::from_u128(0x8D7CC31A_14B9_490F_A5B0_3A2B63DAC4EF);

/// Objects and deliveries still alive; the DLL must stay loaded until there are none.
static LIVE: AtomicUsize = AtomicUsize::new(0);

/// Keeps the DLL loaded for as long as it exists.
struct Alive;

impl Alive {
    fn new() -> Self {
        LIVE.fetch_add(1, Ordering::SeqCst);
        Self
    }
}

impl Drop for Alive {
    fn drop(&mut self) {
        LIVE.fetch_sub(1, Ordering::SeqCst);
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Action {
    Replace,
    SaveCopy,
}

impl Action {
    const ALL: [Self; 2] = [Self::Replace, Self::SaveCopy];

    /// Gracil's own command line for it (see `gracil-ui`'s `request.rs`).
    fn flag(self) -> &'static str {
        match self {
            Self::Replace => "--replace",
            Self::SaveCopy => "--save-copy",
        }
    }
}

/// The COM objects. `#[implement]` writes their reference counting and interface tables as
/// `unsafe` code, generated by `windows-rs` and outside this crate's control, so `unsafe` is
/// allowed in this module only for that. It holds nothing but the declarations.
#[allow(unsafe_code)]
mod objects {
    use std::sync::atomic::AtomicUsize;

    use windows::Win32::System::Com::IClassFactory;
    use windows::Win32::UI::Shell::{IEnumExplorerCommand, IExplorerCommand};
    use windows_core::implement;

    use super::{Action, Alive};

    /// **Gracil (N)**: the entry in Explorer's menu, holding the two commands.
    #[implement(IExplorerCommand)]
    pub(super) struct Menu {
        pub(super) _alive: Alive,
    }

    /// One of the two commands under it.
    #[implement(IExplorerCommand)]
    pub(super) struct Compress {
        pub(super) action: Action,
        pub(super) _alive: Alive,
    }

    /// Hands Explorer the two commands, one at a time.
    #[implement(IEnumExplorerCommand)]
    pub(super) struct Commands {
        pub(super) next: AtomicUsize,
        pub(super) _alive: Alive,
    }

    #[implement(IClassFactory)]
    pub(super) struct Factory {
        pub(super) _alive: Alive,
    }
}

use objects::{
    Commands, Commands_Impl, Compress, Compress_Impl, Factory, Factory_Impl, Menu, Menu_Impl,
};

impl IExplorerCommand_Impl for Menu_Impl {
    fn GetTitle(&self, items: Ref<IShellItemArray>) -> Result<PWSTR> {
        duplicate(&title(media(items.as_ref()).len()))
    }

    fn GetIcon(&self, _items: Ref<IShellItemArray>) -> Result<PWSTR> {
        let gracil = gracil_exe().ok_or(windows_core::Error::from(E_NOTIMPL))?;
        duplicate(&format!("{},0", gracil.display()))
    }

    fn GetToolTip(&self, _items: Ref<IShellItemArray>) -> Result<PWSTR> {
        Err(E_NOTIMPL.into())
    }

    fn GetCanonicalName(&self) -> Result<GUID> {
        Ok(CLSID)
    }

    /// Hidden when nothing selected looks like a video or an image. Only names are read, so this
    /// is quick however Explorer asks (spec §59).
    fn GetState(&self, items: Ref<IShellItemArray>, _ok_to_be_slow: BOOL) -> Result<u32> {
        let state = if media(items.as_ref()).is_empty() {
            ECS_HIDDEN
        } else {
            ECS_ENABLED
        };
        Ok(state.0 as u32)
    }

    fn Invoke(&self, _items: Ref<IShellItemArray>, _context: Ref<IBindCtx>) -> Result<()> {
        // Explorer opens the submenu instead.
        Ok(())
    }

    fn GetFlags(&self) -> Result<u32> {
        Ok(ECF_HASSUBCOMMANDS.0 as u32)
    }

    fn EnumSubCommands(&self) -> Result<IEnumExplorerCommand> {
        Ok(Commands {
            next: AtomicUsize::new(0),
            _alive: Alive::new(),
        }
        .into())
    }
}

impl IExplorerCommand_Impl for Compress_Impl {
    fn GetTitle(&self, _items: Ref<IShellItemArray>) -> Result<PWSTR> {
        let words = selection::Words::get();
        duplicate(match self.action {
            Action::Replace => words.replace,
            Action::SaveCopy => words.save_copy,
        })
    }

    fn GetIcon(&self, _items: Ref<IShellItemArray>) -> Result<PWSTR> {
        Err(E_NOTIMPL.into())
    }

    fn GetToolTip(&self, _items: Ref<IShellItemArray>) -> Result<PWSTR> {
        Err(E_NOTIMPL.into())
    }

    fn GetCanonicalName(&self) -> Result<GUID> {
        Err(E_NOTIMPL.into())
    }

    fn GetState(&self, _items: Ref<IShellItemArray>, _ok_to_be_slow: BOOL) -> Result<u32> {
        Ok(ECS_ENABLED.0 as u32)
    }

    fn Invoke(&self, items: Ref<IShellItemArray>, _context: Ref<IBindCtx>) -> Result<()> {
        let files = media(items.as_ref());
        if !files.is_empty() {
            deliver(self.action, files);
        }
        Ok(())
    }

    fn GetFlags(&self) -> Result<u32> {
        Ok(ECF_DEFAULT.0 as u32)
    }

    fn EnumSubCommands(&self) -> Result<IEnumExplorerCommand> {
        Err(E_NOTIMPL.into())
    }
}

impl IEnumExplorerCommand_Impl for Commands_Impl {
    fn Next(
        &self,
        wanted: u32,
        commands: *mut Option<IExplorerCommand>,
        fetched: *mut u32,
    ) -> HRESULT {
        if commands.is_null() {
            return E_POINTER;
        }
        let mut given = 0;
        while given < wanted as usize {
            let index = self.next.load(Ordering::SeqCst);
            let Some(&action) = Action::ALL.get(index) else {
                break;
            };
            self.next.store(index + 1, Ordering::SeqCst);
            let command: IExplorerCommand = Compress {
                action,
                _alive: Alive::new(),
            }
            .into();
            // SAFETY: Explorer passes room for `wanted` commands, and `given` stays below it.
            #[allow(unsafe_code)]
            unsafe {
                commands.add(given).write(Some(command))
            };
            given += 1;
        }
        if !fetched.is_null() {
            // SAFETY: checked for null; Explorer passes a place for the count when it wants one.
            #[allow(unsafe_code)]
            unsafe {
                fetched.write(given as u32)
            };
        }
        if given == wanted as usize {
            S_OK
        } else {
            S_FALSE
        }
    }

    fn Skip(&self, count: u32) -> Result<()> {
        self.next.fetch_add(count as usize, Ordering::SeqCst);
        Ok(())
    }

    fn Reset(&self) -> Result<()> {
        self.next.store(0, Ordering::SeqCst);
        Ok(())
    }

    fn Clone(&self) -> Result<IEnumExplorerCommand> {
        Ok(Commands {
            next: AtomicUsize::new(self.next.load(Ordering::SeqCst)),
            _alive: Alive::new(),
        }
        .into())
    }
}

impl IClassFactory_Impl for Factory_Impl {
    fn CreateInstance(
        &self,
        outer: Ref<IUnknown>,
        interface: *const GUID,
        object: *mut *mut c_void,
    ) -> Result<()> {
        if interface.is_null() || object.is_null() {
            return Err(E_POINTER.into());
        }
        // SAFETY: checked for null; COM passes a place for the new object.
        #[allow(unsafe_code)]
        unsafe {
            object.write(ptr::null_mut())
        };
        if !outer.is_null() {
            return Err(CLASS_E_NOAGGREGATION.into());
        }
        let menu: IExplorerCommand = Menu {
            _alive: Alive::new(),
        }
        .into();
        // SAFETY: both pointers were checked for null and come from COM, which keeps them valid
        // for the call.
        #[allow(unsafe_code)]
        unsafe {
            menu.query(interface, object).ok()
        }
    }

    fn LockServer(&self, _lock: BOOL) -> Result<()> {
        Ok(())
    }
}

/// How COM gets Gracil's class from this DLL.
///
/// # Safety
///
/// COM calls it with valid pointers or nulls, which are refused.
// SAFETY: the name must be exported unmangled for COM to find it; nothing else has this name.
#[allow(unsafe_code)]
#[unsafe(no_mangle)]
pub unsafe extern "system" fn DllGetClassObject(
    class: *const GUID,
    interface: *const GUID,
    object: *mut *mut c_void,
) -> HRESULT {
    if class.is_null() || interface.is_null() || object.is_null() {
        return E_POINTER;
    }
    // SAFETY: all three were checked for null and come from COM.
    #[allow(unsafe_code)]
    unsafe {
        object.write(ptr::null_mut());
        if class.read() != CLSID {
            return CLASS_E_CLASSNOTAVAILABLE;
        }
        let factory: IClassFactory = Factory {
            _alive: Alive::new(),
        }
        .into();
        factory.query(interface, object)
    }
}

/// Whether Explorer may unload the DLL: only once nothing of it is alive, including a delivery
/// still under way.
// SAFETY: the name must be exported unmangled for COM to find it; nothing else has this name.
#[allow(unsafe_code)]
#[unsafe(no_mangle)]
pub extern "system" fn DllCanUnloadNow() -> HRESULT {
    if LIVE.load(Ordering::SeqCst) == 0 {
        S_OK
    } else {
        S_FALSE
    }
}

/// The selected files that look like videos or images. Folders and things that aren't files are
/// skipped.
fn media(items: Option<&IShellItemArray>) -> Vec<PathBuf> {
    let Some(items) = items else {
        return Vec::new();
    };
    // SAFETY: `items` is a live array Explorer passed for this call; each name Windows hands back
    // is read once and freed once.
    #[allow(unsafe_code)]
    unsafe {
        let count = items.GetCount().unwrap_or(0);
        (0..count)
            .filter_map(|index| {
                let item = items.GetItemAt(index).ok()?;
                let name = item.GetDisplayName(SIGDN_FILESYSPATH).ok()?;
                let path = PathBuf::from(OsString::from_wide(name.as_wide()));
                CoTaskMemFree(Some(name.0 as *const c_void));
                looks_like_media(&path).then_some(path)
            })
            .collect()
    }
}

/// `text` in memory Explorer frees when done with it.
fn duplicate(text: &str) -> Result<PWSTR> {
    let wide: Vec<u16> = text.encode_utf16().chain([0]).collect();
    // SAFETY: `wide` is NUL-terminated and outlives the call, which copies it.
    #[allow(unsafe_code)]
    unsafe {
        SHStrDupW(PCWSTR(wide.as_ptr()))
    }
}

/// `gracil.exe`, which the package installs next to this DLL.
fn gracil_exe() -> Option<PathBuf> {
    let mut module = HMODULE::default();
    let mut buffer = vec![0u16; 32_768];
    // SAFETY: the address is a function in this DLL, so it names this module; the count stays
    // unchanged, so nothing has to be released. The buffer is writable for its whole length.
    #[allow(unsafe_code)]
    let length = unsafe {
        GetModuleHandleExW(
            GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT,
            PCWSTR(gracil_exe as *const () as *const u16),
            &mut module,
        )
        .ok()?;
        GetModuleFileNameW(Some(module), &mut buffer) as usize
    };
    if length == 0 || length >= buffer.len() {
        return None;
    }
    let dll = PathBuf::from(OsString::from_wide(&buffer[..length]));
    Some(dll.with_file_name("gracil.exe"))
}

/// What to start Gracil with. From its package (a manifest beside it), Gracil must be started
/// through the package's alias: started by its path it would run without the package's identity,
/// and its settings and files would end up somewhere else (ADR 0023). Outside a package, the
/// `gracil.exe` beside this DLL.
fn launcher() -> Option<PathBuf> {
    let gracil = gracil_exe()?;
    let packaged = gracil.with_file_name("AppxManifest.xml").is_file();
    let alias = std::env::var_os("LOCALAPPDATA")
        .map(|local| PathBuf::from(local).join(r"Microsoft\WindowsApps\gracil.exe"));
    match alias {
        // The alias is a link with no size, so only its presence is checked.
        Some(alias) if packaged && alias.symlink_metadata().is_ok() => Some(alias),
        _ => Some(gracil),
    }
}

/// Hands the files to Gracil on a thread of its own, so Explorer's menu closes at once (spec §60).
/// Gracil running gets them through the pipe; otherwise it is started with them, and any that
/// don't fit on its command line follow through the pipe once it is up.
fn deliver(action: Action, files: Vec<PathBuf>) {
    let alive = Alive::new();
    let _ = thread::Builder::new()
        .name("gracil-deliver".into())
        .spawn(move || {
            let _alive = alive;
            let flag = OsString::from(action.flag());
            let paths: Vec<OsString> = files.into_iter().map(PathBuf::into_os_string).collect();
            let rest = if gracil_windows::is_running() {
                &paths[..]
            } else {
                let Some(gracil) = launcher() else {
                    return;
                };
                let (first, rest) =
                    selection::split_for_command_line(&paths, selection::COMMAND_LINE_ROOM);
                let mut start = Command::new(&gracil);
                if let Some(folder) = gracil.parent() {
                    start.current_dir(folder);
                }
                // Arguments, never a shell string: every path arrives exactly as it is.
                if start.arg(&flag).args(first).spawn().is_err() {
                    return;
                }
                rest
            };
            if !rest.is_empty() {
                let arguments: Vec<OsString> = [flag].into_iter().chain(rest.to_vec()).collect();
                // Waits for a Gracil still starting; if it never answers, there's no one to tell.
                let _ = gracil_windows::forward(&arguments);
            }
        });
}
